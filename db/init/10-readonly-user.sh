#!/bin/sh
# Creates the read-only account Sage uses (SELECT only on MYSQL_DATABASE).
set -eu
: "${SAGE_READER_USER:?Set SAGE_READER_USER in .env.mysql}"
: "${SAGE_READER_PASSWORD:?Set SAGE_READER_PASSWORD in .env.mysql}"
mysql -uroot -p"$MYSQL_ROOT_PASSWORD" <<SQL
CREATE USER IF NOT EXISTS '${SAGE_READER_USER}'@'%' IDENTIFIED BY '${SAGE_READER_PASSWORD}';
GRANT SELECT, SHOW VIEW ON \`${MYSQL_DATABASE}\`.* TO '${SAGE_READER_USER}'@'%';
FLUSH PRIVILEGES;
SQL
